"""Image-generation prompts for the retro v2 sprite pass.

Every sheet is generated by Codex's built-in ``image_gen`` tool with a real
alpha channel, from three attached references: the character's model sheet
(Image 1), portrait (Image 2) and the project's retro style authority mockup
(Image 3). ``codex_session`` wraps several assets into one ``codex exec`` run.
"""

from __future__ import annotations

from roster_spec import CHARACTERS, CONSTRAINTS, STYLE, job_notes, poses

LAYOUT_TEXT = {
    "row": (
        "Canvas: landscape 3:2. {n} full-body figures in a single row, read left to right, "
        "evenly spaced across the full width with wide empty gaps between them."
    ),
    "rows": (
        "Canvas: landscape 3:2. Two rows of {cols} full-body figures (an invisible grid of {cols} "
        "columns and two rows, read left to right, top row first). Each figure stays inside its "
        "own cell with clear empty space all around it; leave a wide empty band between the "
        "two rows. Both rows use the same character scale."
    ),
    "rows_uneven": (
        "Canvas: landscape 3:2. Two rows of full-body figures ({counts}), read left to right, "
        "top row first, on an invisible grid of {cols} columns. Each figure stays inside its "
        "own cell with clear empty space all around it; leave a wide empty band between the "
        "two rows. Both rows use the same character scale."
    ),
    "grid": (
        "Canvas: landscape 3:2, divided into an invisible 2x2 grid of four equal quadrants (read "
        "left to right, top row first). One full-body figure centred in each quadrant with clear "
        "empty space all around it; nothing crosses into a neighbouring quadrant. All four "
        "figures are drawn at exactly the same scale (the same character height)."
    ),
}

ANIM_LABEL = {
    "basic_attack_1": "basic attack, hit 1",
    "basic_attack_2": "basic attack, hit 2",
    "basic_attack_3": "basic attack, hit 3 (finisher)",
    "up_attack": "upward launcher attack",
    "down_air": "airborne downward spike attack",
    "special_1": "special ability 1",
    "special_2": "special ability 2",
    "movement_ability": "movement ability",
    "ultimate": "ultimate ability",
    "roll_startup": "roll start",
    "roll_recovery": "roll recovery",
    "ledge_hang": "ledge hang",
    "ledge_pull_up": "ledge pull-up",
    "ledge_drop": "ledge drop",
}


def figure_plan(job: dict) -> list[tuple[str, int]]:
    """(animation, frame index) per figure in reading order; anchors are ("anchor", row)."""
    plan: list[tuple[str, int]] = []
    counters: dict[str, int] = {}
    for row_index, row in enumerate(job["rows"]):
        if row["anchor"]:
            plan.append(("anchor", row_index))
        for anim, count in row["anims"]:
            for _ in range(count):
                index = counters.get(anim, 0)
                plan.append((anim, index))
                counters[anim] = index + 1
    return plan


def row_counts(job: dict) -> list[int]:
    if job["layout"] == "grid":
        return [2, 2]
    return [int(row["anchor"]) + sum(c for _, c in row["anims"]) for row in job["rows"]]


def _layout_text(job: dict, n_figures: int) -> str:
    counts = row_counts(job)
    layout = job["layout"]
    if layout == "rows" and len(set(counts)) > 1:
        layout = "rows_uneven"
    return LAYOUT_TEXT[layout].format(
        n=n_figures, cols=max(counts),
        counts="row 1: " + f"{counts[0]} figures; row 2: " + f"{counts[1]} figures" if len(counts) == 2 else "")


def image_prompt(character: str, job: dict) -> str:
    entry = CHARACTERS[character]
    plan = figure_plan(job)
    totals: dict[str, int] = {}
    for anim, index in plan:
        if anim != "anchor":
            totals[anim] = max(totals.get(anim, 0), index + 1)
    lines = [
        "Use case: stylized-concept",
        "Asset type: 2D side-scrolling action game sprite sheet (animation key poses)",
        _layout_text(job, len(plan)),
        f"Character (match Image 1 exactly): {entry['identity']}; {entry['prop']}.",
        "Every figure faces screen-right (looks and moves toward the right edge) in the same "
        "three-quarter side view as a side-scrolling gameplay sprite, and shows the same "
        "character at the same scale. Within a row, standing figures rest their feet on the "
        "same invisible ground line; airborne poses float above it.",
        "Figures:",
    ]
    for number, (anim, index) in enumerate(plan, start=1):
        if anim == "anchor":
            lines.append(
                f"  Figure {number} (scale reference, not part of the animation): "
                f"{entry['name']} standing calmly upright facing right, legs straight, arms relaxed, "
                f"{entry['prop_low']}; not in any fighting stance, so it looks different from every other figure; exactly the height and proportions of the full-body "
                "figures in Image 1.")
        elif anim == "run_check":
            lines.append(
                f"  Figure {number}: an exact repeat of run frame 1, to show the cycle loops.")
        else:
            frames = poses(character, anim)
            label = ANIM_LABEL.get(anim, anim.replace("_", " "))
            lines.append(
                f"  Figure {number} ({label}, frame {index + 1} of {totals[anim]}): "
                f"{frames[index]}.")
    note = job_notes(character, job["job"])
    if note:
        lines.append(f"Animation: {note}")
    lines.append(
        "Backdrop: fully transparent background (a real alpha channel), no colour fill.")
    lines.append(f"Constraints: {CONSTRAINTS}")
    return "\n".join(lines)


def sheet_prompt(character: str, sidecar: dict, canvas: str = "landscape 3:2") -> str:
    """Prompt for a densely planned sheet (plan.py): one scale reference figure,
    then the listed key poses, row by row."""
    entry = CHARACTERS[character]
    counts = sidecar["counts"]
    rows, cols = sidecar["shape"]
    totals: dict[str, int] = {}
    from plan import gen_count  # local import: plan imports this module
    for anim in {f["anim"] for f in sidecar["figures"]} - {"anchor"}:
        totals[anim] = gen_count(character, anim) or 3
    row_lines = []
    start = 1
    for r, count in enumerate(counts, start=1):
        end = start + count - 1
        span = f"figure {start}" if count == 1 else f"figures {start}-{end}"
        row_lines.append(f"row {r}: {span}")
        start = end + 1
    lines = [
        "Use case: stylized-concept",
        "Asset type: 2D side-scrolling action game sprite sheet (animation key poses)",
        f"Canvas: {canvas}. An invisible grid of {rows} rows and {cols} equal columns, read "
        "left to right, top row first (" + "; ".join(row_lines) + "). One full-body figure "
        "centred in each cell with clear empty space all around it; nothing crosses into a "
        "neighbouring cell; leave any unused cells empty. Every figure is drawn at exactly the "
        "same scale (the same character height) as figure 1. Keep a clear empty margin around "
        "the whole grid: no figure, raised weapon or effect may touch the canvas edge, so size "
        "the character small enough that the tallest and widest poses still fit inside their "
        "cells.",
        f"Character (match Image 1 exactly): {entry['identity']}; {entry['prop']}.",
        "Every figure faces screen-right (looks and moves toward the right edge) in the same "
        "three-quarter side view as a side-scrolling gameplay sprite. Standing figures rest "
        "their feet on their row's invisible ground line; airborne poses float above it.",
        f"There are exactly {len(sidecar['figures'])} figures in total; draw every one of "
        "them, including figure 1, the plain standing scale reference.",
        "Figures:",
    ]
    for number, figure in enumerate(sidecar["figures"], start=1):
        anim = figure["anim"]
        if anim == "anchor":
            lines.append(
                f"  Figure {number} (scale reference, not part of any animation): "
                f"{entry['name']} standing calmly upright facing right, legs straight, arms relaxed, "
                f"{entry['prop_low']}; not in any fighting stance, so it looks different from every "
                "other figure; exactly the height and proportions of the full-body "
                "figures in Image 1.")
            continue
        index = figure["index"]
        label = ANIM_LABEL.get(anim, anim.replace("_", " "))
        lines.append(
            f"  Figure {number} ({label}, key pose {index + 1} of {totals[anim]}): "
            f"{poses(character, anim)[index]}.")
    lines.append(
        "Backdrop: fully transparent background (a real alpha channel), no colour fill.")
    lines.append(f"Constraints: {CONSTRAINTS}")
    return "\n".join(lines)


def model_sheet_prompt(character: str, variant_note: str = "") -> str:
    entry = CHARACTERS[character]
    lines = [
        "Use case: stylized-concept",
        "Asset type: 2D side-view action game character model sheet (sprite production reference)",
        "Canvas: landscape 3:2.",
        f"Character: {entry['identity']}; {entry['prop']}.",
        "Three full-body views side by side at exactly the same scale, all standing on one "
        "shared invisible ground line, separated by wide empty gaps:",
        "  (1) left: facing screen-right in a ready idle stance, in the three-quarter side view "
        f"of a side-scrolling gameplay sprite, {entry['prop_low']};",
        "  (2) middle: front view, neutral standing pose;",
        f"  (3) right: facing screen-right in a dynamic action pose wielding the prop, with "
        f"{entry['effect']}.",
        "Backdrop: fully transparent background (a real alpha channel), no colour fill.",
        f"Constraints: {CONSTRAINTS}",
    ]
    if variant_note:
        lines.insert(4, variant_note)
    return "\n".join(lines)


def codex_session(character: str, assets: list[tuple[str, str]], references: list[str],
                  size_note: str = "") -> str:
    """One ``codex exec`` prompt that generates ``assets`` [(file name, prompt)]."""
    name = CHARACTERS[character]["name"]
    ref_roles = [
        f"Image 1: {name}'s character model sheet - the exact design to match (face, hair, "
        "costume, colours, props, proportions).",
        f"Image 2: {name}'s portrait - face and costume detail.",
        "Image 3: the game's retro art-style authority mockup - linework, rendering and palette.",
    ][: len(references)]
    parts = [
        "Use the imagegen skill with its built-in image_gen tool (do NOT use the CLI fallback "
        f"script). Make exactly {len(assets)} image_gen calls, one per asset below, in order. "
        "After each call, copy the generated PNG from $CODEX_HOME/generated_images into the "
        "current working directory under that asset's file name (a byte-for-byte copy; never "
        "edit pixels). When all are done, print one line per asset: "
        "\"<file name> <- <source path>\". Do nothing else: no code, no extra images, no edits."
        + (f" {size_note}" if size_note else ""),
        "",
        "Attached reference images (references only, never edit targets):",
        *[f"- {role}" for role in ref_roles],
        "",
        f"Shared style for every asset: {STYLE}",
        "",
    ]
    for number, (file_name, prompt) in enumerate(assets, start=1):
        parts.append(f"Asset {number} -> {file_name}")
        parts.append(prompt)
        parts.append("")
    return "\n".join(parts)
